#!/usr://usr/bin/env python3
"""Check Soroban symbol_short! literals and document their meanings."""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PATTERN = re.compile(r'symbol_short!\s*\(\s*"([^"]*)"\s*\)')

uses: dict[str, list[tuple[Path, int]]] = {}

for base in (ROOT / "src", ROOT / "contracts", ROOT / "tests"):
    if not base.exists():
        continue
    for path in sorted(base.rglob("*.rs")):
        text = path.read_text(encoding="utf-8")
        for line_number, line in enumerate(text.splitlines(), 1):
            for symbol in PATTERN.findall(line):
                uses.setdefault(symbol, []).append(
                    (path.relative_to(ROOT).as_posix(), line_number)
                )

errors: list[str] = []

for symbol, locations in sorted(uses.items()):
    if len(symbol) > 9:
        errors.append(
            f"symbol_short! literal {symbol!r} is {len(symbol)} characters (maximum 9)"
        )

    unique_locations = sorted(set(locations))
    if len(unique_locations) > 1:
        files = sorted({path for path, _ in unique_locations})
        if len(files) > 1:
            meanings = ", ".join(
                f"{path}:{line}" for path, line in unique_locations
            )
            errors.append(
                f"symbol_short! literal {symbol!r} is reused in multiple files "
                f"(potential collision): {meanings}"
            )

table = [
    "# Short Symbol Table",
    "",
    "Generated by `scripts/check_symbol_short.py`.",
    "",
    "| Symbol | Locations |",
    "|---|---|",
]
for symbol, locations in sorted(uses.items()):
    location_text = "<br>".join(
        f"`{path}:{line}`" for path, line in sorted(set(locations))
    )
    table.append(f"| `{symbol}` | {location_text} |")

OUTPUT = ROOT / "docs" / "SYMBOLS.md"
OUTPUT.write_text("\n".join(table) + "\n", encoding="utf-8")

if errors:
    print("symbol_short! lint failed:")
    for error in errors:
        print(f"- {error}")
    sys.exit(1)

print(f"OK: {len(uses)} unique symbol_short! literals are at most 9 characters.")
